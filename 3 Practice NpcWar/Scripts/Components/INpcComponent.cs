using System;

namespace TowerDefense;

// Контракт компонента, который менеджер НПС может присвоить НПС.
// Каждый компонент реализует его сам: вес и набор заполняемых
// числовых переменных задаются внутри конкретного компонента.
public interface INpcComponent
{
    // Апгрейд интерфейса умножает его статы на эту величину.
    const float UpgradeMultiplier = 1.2f;

    // Максимум апгрейдов на один интерфейс.
    const int MaxUpgrades = 3;

    // Вес компонента по умолчанию.
    const int DefaultWeight = 1;

    // Вес компонента: по нему менеджер решает, достанется ли компонент НПС.
    int GetWeight();

    // Массив сеттеров числовых переменных компонента.
    // Оставлен для возможного заполнения извне: сейчас компоненты
    // используют собственные значения из [Export].
    Action<float>[] GetStatSetters();

    // Применяет указанное количество апгрейдов к статам компонента.
    void ApplyUpgrades(int count);
}
